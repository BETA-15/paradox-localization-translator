def render_original_expression(expression, samples):
    if isinstance(expression, ast.Constant) and isinstance(expression.value, str):
        return expression.value
    if isinstance(expression, ast.JoinedStr):
        rendered = []
        for part in expression.values:
            if isinstance(part, ast.Constant):
                rendered.append(part.value)
                continue
            sample = next(samples)
            if part.format_spec is not None:
                spec = "".join(value.value for value in part.format_spec.values)
                sample = float(sample) if spec.endswith("f") else sample
            elif part.conversion in (ord("r"), ord("a")):
                sample = ast.literal_eval(sample)
            evaluated = ast.JoinedStr(values=[ast.FormattedValue(
                value=ast.Constant(sample), conversion=part.conversion,
                format_spec=part.format_spec)])
            rendered.append(eval(compile(ast.fix_missing_locations(ast.Expression(evaluated)),
                                         "original display", "eval"), {"__builtins__": {}}))
        return "".join(rendered)
    if isinstance(expression, ast.BinOp) and isinstance(expression.op, ast.Add):
        return render_original_expression(expression.left, samples) + render_original_expression(expression.right, samples)
    return str(next(samples))


@pytest.mark.parametrize("case, migrated", list(zip(ORIGINAL_DISPLAY_CASES, MIGRATED_LITERALS)))
def test_original_expression_matches_the_japanese_translation(case, migrated):
    key, fields, expected = case
    assert key == migrated[1]
    expression = ast.parse("(" + migrated[2] + ")", mode="eval").body
    samples = iter(value for name, value in fields.items() if name != "target_name")
    original = render_original_expression(expression, samples)
    if key == "u6.gaps_in_source_text_english_and":
        original += fields["notices"]
    assert original == expected
    i18n.set_ui_language("japanese")
    assert i18n.t(key, **fields) == original
