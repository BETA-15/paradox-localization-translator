def test_remaining_internal_values_are_unchanged():
    import sys
    from collections import defaultdict
    root = Path(__file__).parents[1]
    sys.path.insert(0, str(root / "tools"))
    import i18n_scan
    current = defaultdict(list)
    for row in i18n_scan.japanese_strings(root / "app/main.py"):
        if row["owner"] in INTERNAL_VALUES_BY_OWNER:
            current[row["owner"]].append(row["text"])
    assert dict(current) == INTERNAL_VALUES_BY_OWNER


def test_japanese_language_classification_is_complete():
    classified = {(owner, original) for owner, original, _, _ in JAPANESE_LANGUAGE_CLASSIFICATION}
    for _, original, _, _, owner in ORIGINAL_CASES:
        if "日本語" in original:
            assert (owner, original) in classified
    for owner, values in INTERNAL_VALUES_BY_OWNER.items():
        for original in values:
            if "日本語" in original:
                assert (owner, original) in classified
